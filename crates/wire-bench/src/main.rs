//! The wire-format spike (plan §11.5): the same event pages encoded as columnar blocks with a dictionary, as
//! protobuf messages, with rkyv and with `FlatBuffers`; their sizes raw and with zstd, and the time to encode them and to
//! read them back (decode, then scan two fields of every event). `cargo run --release -p snitchhiker-wire-bench`.

use std::collections::{HashMap, HashSet};
use std::hint::black_box;
use std::io::Write as _;
use std::time::{Duration, Instant};

use prost::Message as _;
use snitchhiker_proto::columns::{EventBlock, EventRow, encode_events};
use snitchhiker_proto::v1;

