/// A page of events as the daemon keeps them: a few programs, more hosts, ports that repeat.
#[derive(Clone, rkyv::Archive, rkyv::Serialize, rkyv::Deserialize)]
struct Event {
    seq: i64,
    time_ms: u64,
    exe: String,
    host: String,
    uid: u32,
    pid: u32,
    address: [u8; 16],
    port: u16,
    protocol: u8,
    context: u8,
    action: u8,
    source: u8,
    rule: u64,
    bytes_out: u64,
    bytes_in: u64,
}

/// A small deterministic generator, so every run measures the same data.
struct Random(u64);

impl Random {
    fn next(&mut self) -> u64 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        self.0
    }

    fn below(&mut self, n: u64) -> u64 {
        self.next() % n
    }
}

fn events(count: usize) -> Vec<Event> {
    let mut random = Random(0x5eed_1234_abcd_ef01);
    let programs: Vec<String> = (0..20)
        .map(|i| format!("/usr/lib/program-{i}/bin/program-{i}"))
        .collect();
    let hosts: Vec<String> = (0..200)
        .map(|i| format!("service-{i}.region-{}.example.com", i % 7))
        .collect();
    let mut time = 1_763_200_000_000;
    (0..count)
        .map(|i| {
            time += random.below(2_000);
            let program = usize::try_from(random.below(20)).unwrap_or(0);
            let host = usize::try_from(random.below(200)).unwrap_or(0);
            let mut address = [0_u8; 16];
            address[10] = 0xff;
            address[11] = 0xff;
            address[12..].copy_from_slice(&[198, 51, 100, u8::try_from(host % 250).unwrap_or(0)]);
            Event {
                seq: 1_000_000 + i64::try_from(i).unwrap_or(0),
                time_ms: time,
                exe: programs.get(program).cloned().unwrap_or_default(),
                host: if random.below(10) == 0 {
                    String::new()
                } else {
                    hosts.get(host).cloned().unwrap_or_default()
                },
                uid: if random.below(5) == 0 { 0 } else { 1000 },
                pid: 1000 + u32::try_from(program).unwrap_or(0) * 37,
                address,
                port: [443, 443, 443, 80, 53]
                    .get(usize::try_from(random.below(5)).unwrap_or(0))
                    .copied()
                    .unwrap_or(443),
                protocol: if random.below(6) == 0 { 17 } else { 6 },
                context: 1,
                action: 1,
                source: 1,
                rule: 18 + random.below(30),
                bytes_out: random.below(100_000),
                bytes_in: random.below(10_000_000),
            }
        })
        .collect()
}

/// What each reader computes, so they can be checked against each other.
#[derive(Debug, PartialEq, Eq)]
struct Scan {
    bytes_out: u64,
    programs: usize,
}

trait Format {
    fn name(&self) -> &'static str;
    fn encode(&self, events: &[Event]) -> Vec<u8>;
    fn scan(&self, encoded: &[u8]) -> Scan;
}

struct Protobuf;

impl Format for Protobuf {
    fn name(&self) -> &'static str {
        "protobuf messages"
    }

    fn encode(&self, events: &[Event]) -> Vec<u8> {
        v1::EventPage {
            scanned_from: 0,
            events: events
                .iter()
                .map(|e| v1::ConnectionEvent {
                    seq: e.seq,
                    time_ms: e.time_ms,
                    exe: e.exe.clone(),
                    host: e.host.clone(),
                    uid: e.uid,
                    pid: e.pid,
                    protocol: u32::from(e.protocol),
                    address: e.address[12..].to_vec(),
                    port: u32::from(e.port),
                    context: i32::from(e.context),
                    action: i32::from(e.action),
                    source: i32::from(e.source),
                    rule: Some(e.rule),
                    bytes_out: e.bytes_out,
                    bytes_in: e.bytes_in,
                })
                .collect(),
        }
        .encode_to_vec()
    }

    fn scan(&self, encoded: &[u8]) -> Scan {
        let page = v1::EventPage::decode(encoded).unwrap_or_default();
        let programs: HashSet<&str> = page.events.iter().map(|e| e.exe.as_str()).collect();
        Scan {
            bytes_out: page.events.iter().map(|e| e.bytes_out).sum(),
            programs: programs.len(),
        }
    }
}

struct Columnar;

impl Format for Columnar {
    fn name(&self) -> &'static str {
        "columnar block + dictionary"
    }

    fn encode(&self, events: &[Event]) -> Vec<u8> {
        // The daemon's interned ids; the dictionary travels once, in the same message.
        // The daemon has its strings' ids already (it interns them as it records); a map stands in for that here.
        fn id<'a>(
            ids: &mut HashMap<&'a str, u32>,
            strings: &mut Vec<&'a str>,
            text: &'a str,
        ) -> u32 {
            if text.is_empty() {
                return 0;
            }
            *ids.entry(text).or_insert_with(|| {
                strings.push(text);
                u32::try_from(strings.len()).unwrap_or(0)
            })
        }
        let mut strings: Vec<&str> = Vec::new();
        let mut ids: HashMap<&str, u32> = HashMap::new();
        let rows: Vec<EventRow> = events
            .iter()
            .map(|e| EventRow {
                seq: e.seq,
                time_ms: e.time_ms,
                exe: id(&mut ids, &mut strings, &e.exe),
                host: id(&mut ids, &mut strings, &e.host),
                uid: e.uid,
                pid: e.pid,
                address: e.address,
                port: e.port,
                protocol: e.protocol,
                context: e.context,
                action: e.action,
                source: e.source,
                rule: e.rule,
                bytes_out: e.bytes_out,
                bytes_in: e.bytes_in,
            })
            .collect();
        let mut columns = Vec::new();
        let _ = encode_events(&rows, &mut columns);
        v1::EventBlock {
            scanned_from: 0,
            columns: columns.into(),
            dictionary: Some(v1::Dictionary {
                ids: (1..=u32::try_from(strings.len()).unwrap_or(0)).collect(),
                values: strings.iter().map(|s| (*s).to_owned()).collect(),
            }),
        }
        .encode_to_vec()
    }

    fn scan(&self, encoded: &[u8]) -> Scan {
        let message = v1::EventBlock::decode(encoded).unwrap_or_default();
        let Ok(block) = EventBlock::parse(&message.columns) else {
            return Scan {
                bytes_out: 0,
                programs: 0,
            };
        };
        let programs: HashSet<u32> = block.exe_ids().collect();
        Scan {
            bytes_out: block.rows().map(|r| r.bytes_out).sum(),
            programs: programs.len(),
        }
    }
}

struct Rkyv;

impl Format for Rkyv {
    fn name(&self) -> &'static str {
        "rkyv (validated)"
    }

    fn encode(&self, events: &[Event]) -> Vec<u8> {
        rkyv::to_bytes::<rkyv::rancor::Error>(&events.to_vec())
            .map_or_else(|_| Vec::new(), |bytes| bytes.to_vec())
    }

    fn scan(&self, encoded: &[u8]) -> Scan {
        // rkyv reads aligned buffers: what arrives off a socket is copied into one first.
        let mut aligned = rkyv::util::AlignedVec::<16>::new();
        aligned.extend_from_slice(encoded);
        let Ok(events) = rkyv::access::<rkyv::Archived<Vec<Event>>, rkyv::rancor::Error>(&aligned)
        else {
            return Scan {
                bytes_out: 0,
                programs: 0,
            };
        };
        let programs: HashSet<&str> = events.iter().map(|e| e.exe.as_str()).collect();
        Scan {
            bytes_out: events.iter().map(|e| e.bytes_out.to_native()).sum(),
            programs: programs.len(),
        }
    }
}

struct FlatBuffers;

impl Format for FlatBuffers {
    fn name(&self) -> &'static str {
        "FlatBuffers (verified)"
    }

    fn encode(&self, events: &[Event]) -> Vec<u8> {
        let mut builder = flatbuffers::FlatBufferBuilder::new();
        let offsets: Vec<_> = events
            .iter()
            .map(|e| {
                let exe = builder.create_string(&e.exe);
                let host = builder.create_string(&e.host);
                let address = builder.create_vector(&e.address);
                fb::Event::create(
                    &mut builder,
                    &fb::EventArgs {
                        seq: e.seq,
                        time_ms: e.time_ms,
                        exe: Some(exe),
                        host: Some(host),
                        uid: e.uid,
                        pid: e.pid,
                        address: Some(address),
                        port: e.port,
                        protocol: e.protocol,
                        context: e.context,
                        action: e.action,
                        source: e.source,
                        rule: e.rule,
                        bytes_out: e.bytes_out,
                        bytes_in: e.bytes_in,
                    },
                )
            })
            .collect();
        let events = builder.create_vector(&offsets);
        let page = fb::Page::create(
            &mut builder,
            &fb::PageArgs {
                events: Some(events),
            },
        );
        builder.finish(page, None);
        builder.finished_data().to_vec()
    }

    fn scan(&self, encoded: &[u8]) -> Scan {
        let Ok(page) = fb::root_as_page(encoded) else {
            return Scan {
                bytes_out: 0,
                programs: 0,
            };
        };
        let events = page.events().unwrap_or_default();
        let programs: HashSet<&str> = events.iter().filter_map(|e| e.exe()).collect();
        Scan {
            bytes_out: events.iter().map(|e| e.bytes_out()).sum(),
            programs: programs.len(),
        }
    }
}

/// The fastest of `runs` runs of `f`.
fn fastest(runs: usize, mut f: impl FnMut()) -> Duration {
    (0..runs)
        .map(|_| {
            let start = Instant::now();
            f();
            start.elapsed()
        })
        .min()
        .unwrap_or_default()
}

fn main() {
    const EVENTS: usize = 10_000;
    const RUNS: usize = 30;
    let events = events(EVENTS);
    let formats: [&dyn Format; 4] = [&Columnar, &Protobuf, &Rkyv, &FlatBuffers];
    let mut out = std::io::stdout().lock();
    let _ = writeln!(
        out,
        "{EVENTS} events, fastest of {RUNS} runs\n\n| Format | Bytes/event | With zstd (3) | Encode ns/event | Read ns/event |\n| --- | --- | --- | --- | --- |"
    );
    let mut reference = None;
    for format in formats {
        let encoded = format.encode(&events);
        let scan = format.scan(&encoded);
        assert!(
            reference.get_or_insert(Scan {
                bytes_out: scan.bytes_out,
                programs: scan.programs,
            }) == &scan,
            "{} read back something else",
            format.name()
        );
        let compressed = zstd::encode_all(encoded.as_slice(), 3).unwrap_or_default();
        let encode = fastest(RUNS, || {
            black_box(format.encode(black_box(&events)));
        });
        let read = fastest(RUNS, || {
            black_box(format.scan(black_box(&encoded)));
        });
        let per = |value: f64| value / f64::from(u32::try_from(EVENTS).unwrap_or(1));
        let _ = writeln!(
            out,
            "| {} | {:.1} | {:.1} | {:.0} | {:.0} |",
            format.name(),
            per(f64::from(u32::try_from(encoded.len()).unwrap_or(u32::MAX))),
            per(f64::from(
                u32::try_from(compressed.len()).unwrap_or(u32::MAX)
            )),
            per(encode.as_secs_f64() * 1e9),
            per(read.as_secs_f64() * 1e9),
        );
    }
}
